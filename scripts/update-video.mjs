import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(SCRIPT_DIR, "..");
const VIDEO_PATH = path.join(PROJECT_ROOT, "docs/assets/pi-working-phrase-demo.mp4");
const IMAGE_PATH = path.join(PROJECT_ROOT, "docs/assets/pi-working-phrase-demo.png");
const TAPE_PATH = path.join(PROJECT_ROOT, ".video/pi-working-phrase-demo.tape");
const PACKAGE_JSON_PATH = path.join(PROJECT_ROOT, "package.json");
const DEFAULT_BRANCH = process.env.PI_VIDEO_BRANCH ?? "main";
const EXPLICIT_VIDEO_URL = process.env.PI_VIDEO_URL;
const EXPLICIT_IMAGE_URL = process.env.PI_IMAGE_URL;
const PREVIEW_IMAGE_TIMESTAMP = process.env.PI_IMAGE_TIMESTAMP ?? "00:00:02.000";
const DEMO_DURATION_MS = process.env.PI_WORKING_PHRASE_DEMO_MS ?? "17000";
const DEMO_PHRASE_SHUFFLE_MS = process.env.PI_WORKING_PHRASE_DEMO_PHRASE_MS ?? "1500";

const args = new Set(process.argv.slice(2));
const dryRun = args.has("--dry-run");
const skipRecord = args.has("--skip-record");

function relativePath(filePath) {
	return path.relative(PROJECT_ROOT, filePath).split(path.sep).join("/");
}

function commandExists(command) {
	const lookup = process.platform === "win32" ? "where" : "which";
	const result = spawnSync(lookup, [command], {
		cwd: PROJECT_ROOT,
		stdio: "ignore",
	});

	return result.status === 0;
}

function requireCommands(commands) {
	const missing = commands.filter((command) => !commandExists(command));
	if (missing.length === 0) return;

	throw new Error(
		[
			`Missing required recorder command(s): ${missing.join(", ")}`,
			"",
			"Install VHS and its recorder dependencies, then retry:",
			"  macOS:  brew install vhs ffmpeg ttyd",
			"  Linux:  see https://github.com/charmbracelet/vhs#installation",
			"",
			"VHS is used because it scripts a headless terminal session and can output MP4 directly.",
		].join("\n"),
	);
}

function createTape() {
	const videoOutput = relativePath(VIDEO_PATH);

	return `# Generated by npm run video:update. Edit scripts/update-video.mjs instead.
Output ${videoOutput}

Set Shell bash
Set FontSize 25
Set Width 760
Set Height 96
Set Theme "Catppuccin Mocha"
Set Margin 0
Set Padding 18
Set LineHeight 1.2
Set Framerate 30
Set CursorBlink false
Set TypingSpeed 35ms
Env PI_WORKING_PHRASE_VIDEO_COMPACT "true"
Env PI_WORKING_PHRASE_DEMO_MS "${DEMO_DURATION_MS}"
Env PI_WORKING_PHRASE_DEMO_PHRASE_MS "${DEMO_PHRASE_SHUFFLE_MS}"

Hide
Type "npm run video:demo"
Enter
Sleep 800ms
Show
Sleep 15s
Hide
Sleep 2s
`;
}

function normalizeGitHubRepository(repository) {
	const repositoryUrl = typeof repository === "string" ? repository : repository?.url;
	if (!repositoryUrl) return undefined;

	return repositoryUrl
		.replace(/^git\+/, "")
		.replace(/^https:\/\/github\.com\//, "")
		.replace(/^git@github\.com:/, "")
		.replace(/\.git$/, "")
		.replace(/^\/+|\/+$/g, "");
}

function getAssetUrl(packageJson, assetPath, explicitUrl, environmentVariableName) {
	if (explicitUrl) return explicitUrl;

	const repositorySlug = normalizeGitHubRepository(packageJson.repository);
	if (!repositorySlug || repositorySlug.includes("://")) {
		throw new Error(
			`Could not derive a GitHub raw asset URL from package.json repository. Set ${environmentVariableName} and rerun.`,
		);
	}

	return `https://raw.githubusercontent.com/${repositorySlug}/${DEFAULT_BRANCH}/${assetPath}`;
}

function getVideoUrl(packageJson) {
	return getAssetUrl(packageJson, "docs/assets/pi-working-phrase-demo.mp4", EXPLICIT_VIDEO_URL, "PI_VIDEO_URL");
}

function getImageUrl(packageJson) {
	return getAssetUrl(packageJson, "docs/assets/pi-working-phrase-demo.png", EXPLICIT_IMAGE_URL, "PI_IMAGE_URL");
}

function updatePackageJson() {
	const packageJson = JSON.parse(readFileSync(PACKAGE_JSON_PATH, "utf8"));
	packageJson.pi = packageJson.pi ?? {};
	packageJson.pi.video = getVideoUrl(packageJson);
	packageJson.pi.image = getImageUrl(packageJson);

	if (dryRun) {
		console.log(`[dry-run] Would set package.json pi.video to ${packageJson.pi.video}`);
		console.log(`[dry-run] Would set package.json pi.image to ${packageJson.pi.image}`);
		return;
	}

	writeFileSync(PACKAGE_JSON_PATH, `${JSON.stringify(packageJson, null, "\t")}\n`);
	console.log(`Updated package.json pi.video -> ${packageJson.pi.video}`);
	console.log(`Updated package.json pi.image -> ${packageJson.pi.image}`);
}

function recordVideo() {
	if (skipRecord) {
		console.log("Skipping VHS recording because --skip-record was provided.");
		return;
	}

	if (dryRun) {
		console.log(`[dry-run] Would require recorder commands: vhs, ffmpeg, ttyd`);
		console.log(`[dry-run] Would run: vhs ${relativePath(TAPE_PATH)}`);
		return;
	}

	requireCommands(["vhs", "ffmpeg", "ttyd"]);

	const result = spawnSync("vhs", [relativePath(TAPE_PATH)], {
		cwd: PROJECT_ROOT,
		stdio: "inherit",
	});

	if (result.error) throw result.error;
	if (result.status !== 0) throw new Error(`vhs exited with status ${result.status ?? "unknown"}`);
	if (!existsSync(VIDEO_PATH)) throw new Error(`VHS completed but did not create ${relativePath(VIDEO_PATH)}`);
}

function generatePreviewImage() {
	if (dryRun) {
		console.log(
			`[dry-run] Would extract ${relativePath(IMAGE_PATH)} from ${relativePath(VIDEO_PATH)} at ${PREVIEW_IMAGE_TIMESTAMP}`,
		);
		return;
	}

	requireCommands(["ffmpeg"]);
	if (!existsSync(VIDEO_PATH)) {
		throw new Error(`Cannot create ${relativePath(IMAGE_PATH)} because ${relativePath(VIDEO_PATH)} does not exist.`);
	}

	const result = spawnSync(
		"ffmpeg",
		[
			"-y",
			"-loglevel",
			"error",
			"-ss",
			PREVIEW_IMAGE_TIMESTAMP,
			"-i",
			relativePath(VIDEO_PATH),
			"-frames:v",
			"1",
			"-vf",
			"scale=760:-1",
			relativePath(IMAGE_PATH),
		],
		{
			cwd: PROJECT_ROOT,
			stdio: "inherit",
		},
	);

	if (result.error) throw result.error;
	if (result.status !== 0) throw new Error(`ffmpeg exited with status ${result.status ?? "unknown"}`);
	if (!existsSync(IMAGE_PATH)) throw new Error(`ffmpeg completed but did not create ${relativePath(IMAGE_PATH)}`);
	console.log(`Updated ${relativePath(IMAGE_PATH)} from ${relativePath(VIDEO_PATH)}`);
}

function printSummary() {
	const packageJson = JSON.parse(readFileSync(PACKAGE_JSON_PATH, "utf8"));
	console.log("");
	console.log("Preview asset update complete.");
	console.log(`- Video file: ${relativePath(VIDEO_PATH)}`);
	console.log(`- Image file: ${relativePath(IMAGE_PATH)}`);
	console.log(`- Tape file: ${relativePath(TAPE_PATH)}`);
	console.log(`- pi.video:   ${packageJson.pi?.video ?? "not set"}`);
	console.log(`- pi.image:   ${packageJson.pi?.image ?? "not set"}`);
	console.log("");
	console.log("If this is for the marketplace, commit the MP4, PNG, and package.json after reviewing the assets.");
}

try {
	mkdirSync(path.dirname(VIDEO_PATH), { recursive: true });
	mkdirSync(path.dirname(TAPE_PATH), { recursive: true });
	writeFileSync(TAPE_PATH, createTape());
	console.log(`Wrote ${relativePath(TAPE_PATH)}`);

	if (dryRun) {
		execFileSync(process.execPath, ["--version"], { stdio: "ignore" });
	}

	recordVideo();
	generatePreviewImage();
	updatePackageJson();
	printSummary();
} catch (error) {
	console.error(error instanceof Error ? error.message : error);
	process.exitCode = 1;
}
